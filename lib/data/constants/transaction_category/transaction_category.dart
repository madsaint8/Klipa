  /// Map from DB transaction_type string → enum
  static TransactionCategory fromString(String? type, String? txType) {
    return switch (type?.toLowerCase()) {
      'airtime' => TransactionCategory.airtimeTopUp,
      'data' => TransactionCategory.dataBundle,
      'electricity' => TransactionCategory.electricity,
      'tv' || 'dstv' || 'netflix' => TransactionCategory.tvSubscription,
