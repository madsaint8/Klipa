      'crypto_swap' => TransactionCategory.cryptoSwap,
      'staking' => TransactionCategory.staking,
      'shopping' => TransactionCategory.onlineShopping,
      'p2p' => TransactionCategory.peerToPeer,
      'subscription' => TransactionCategory.subscriptionPayment,
      'transfer' => txType == 'credit'
          ? TransactionCategory.receiveMoney
          : TransactionCategory.sendMoney,
      'deposit' => TransactionCategory.bankDeposit,
      'withdrawal' => TransactionCategory.bankWithdrawal,
      _ => TransactionCategory.unknown,
    };
