class ProfileData {
  String name;
  String surname;
  String userName;
  String userId;
  String status;
  String email;
  String phoneNumber;

 
  ProfileData({
    required this.name,
    required this.status,
    required this.email,
    required this.phoneNumber,
    required this.userId,
    required this.userName,
    required this.surname,
  });
}